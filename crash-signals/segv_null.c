/*
 * segv_null.c —— 空指针解引用
 *
 * 预期信号: SIGSEGV (11)  →  退出码 139 (128+11)
 *
 * 为什么崩:
 *   地址 0x0 位于内核为进程保留的"空指针陷阱页"——它没有被映射到任何段,
 *   页表标记为不可访问。CPU 执行写指令时发现该虚拟地址无对应物理页且无权限,
 *   抛出缺页/保护异常,内核把它转成 SIGSEGV 发回本进程。
 *   崩溃点就是这条 store 指令本身(同步信号)。
 *
 * dmesg 特征: "segfault at 0 ip ..." —— 出错地址 0 即空指针实锤。
 */
int main(void) {
    volatile int *p = (int *)0;   /* volatile 防止编译器把无副作用的写优化掉 */
    *p = 42;                      /* 往地址 0x0 写 → SIGSEGV */
    return 0;
}
