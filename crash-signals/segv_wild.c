/*
 * segv_wild.c —— 野指针 / 未初始化指针解引用
 *
 * 预期信号: SIGSEGV (11)  →  退出码 139  (也可能是 SIGBUS/其它,取决于垃圾值落点)
 *
 * 为什么崩:
 *   未初始化的指针 p 里是栈上的"垃圾值"——一个几乎肯定不指向任何合法映射的
 *   随机地址。往这个随机地址写,大概率落在未映射区域 → SIGSEGV。
 *   与空指针的区别只在"出错地址"：野指针的地址五花八门、不为 0。
 *
 * dmesg 特征: "segfault at <一个很大的随机值>" —— 非 0 随机地址即野指针特征。
 *
 * 注意: 这是未定义行为(UB),不同编译器/优化等级下的具体地址和信号可能不同,
 *       极小概率那个垃圾地址恰好可写而不崩(所以 UB 不可依赖)。
 */
int main(void) {
    int *p;            /* 故意不初始化: p 是栈垃圾值 */
    *p = 42;           /* 往随机地址写 → 大概率 SIGSEGV */
    return 0;
}
